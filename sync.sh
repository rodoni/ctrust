#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$SCRIPT_DIR"
CMD="${1:-help}"

usage() {
    cat <<EOF
Usage: ./sync.sh <command|target> [args...]

Available targets (Deploy):
  generic     [dest] Deploy to .ctrust/{agents,skills,scripts,tools}
  antigravity [dest] Deploy agents/skills to .agents and scripts/tools to .ctrust
  opencode    [dest] Deploy agents/skills to .opencode and scripts/tools to .ctrust
  kilocode    [dest] Deploy agents/skills to .kilo and scripts/tools to .ctrust
  cursor      [dest] Deploy agents/skills to .cursor and scripts/tools to .ctrust
  claude      [dest] Deploy agents/skills to .claude and scripts/tools to .ctrust
  all         [dest] Deploy to all supported targets

Utility commands:
  init [dest]             Initialize .ctrust migration state in a project
  upgrade-state [dest]    Upgrade legacy migration.yaml to schema version 2
  reconcile-artifacts [dest] Reconcile .ctrust artifacts deterministically
  validate-artifacts [dest] Validate .ctrust artifacts without writing
  plan-slices [dest]      Create one plan Markdown file for every slice
  organize [dest]         Generate the deterministic organization plan
  validate-organization [dest] Validate organization without writing
  resume [dest] [--brief|--full] Print recovery context (default --brief)
  function-map [dest]     Validate/enrich function-level map
  select-function [dest]  Select the next function unit
  record-implementation [dest] <unit> <rust_file> <module_path>
  record-evidence [dest] <unit> <evidence_path>
  verify-slice [dest] [slice] Run migration gates, checkpoint and advance
  compare [dest] <unit> <passed|failed>
  checkpoint [dest] [title] Create a numbered recovery checkpoint
  next [dest] <action> [command] Record one next action
  failed [dest] <reason>  Record failure and stop after max_attempts
  contract [dest] [unit] Create a draft contract and unit plan
  inventory [dest] [slice] Export inventory transactionally from the manifest
  recover [dest]         Execute one eligible mechanical recovery
  model [dest] [unit]     Create Rust model template (confirmed contract required)
  clean <target> [dest]   Remove only files previously generated by ctrust
  list                  List available agents, skills and scripts
  verify                Check ctrust structure and shell syntax
  help                  Show this help message

Examples:
  ./sync.sh generic /path/to/project
  ./sync.sh kilocode /path/to/project
  ./sync.sh all /path/to/project
  ./sync.sh list
  ./sync.sh verify
  ./sync.sh clean generic /path/to/project
EOF
}

source_file() {
    local path="$1"
    [ -f "$path" ] || {
        echo "Error: source file not found: $path" >&2
        return 1
    }
}

install_file() {
    local source="$1"
    local destination="$2"
    source_file "$source"
    mkdir -p "$(dirname "$destination")"

    if [ -f "$destination" ]; then
        if cmp -s "$source" "$destination"; then
            echo "  unchanged $destination"
        else
            echo "  conflict  $destination (preserved existing file)" >&2
        fi
        return 0
    fi

    cp "$source" "$destination"
    chmod --reference="$source" "$destination" 2>/dev/null || true
    echo "  installed $destination"
}

install_agents_and_skills() {
    local root="$1"
    local agent
    local skill

    for agent in "$REPO_ROOT/agents/"*.md; do
        [ -f "$agent" ] || continue
        install_file "$agent" "$root/agents/$(basename "$agent")"
    done

    for skill in "$REPO_ROOT/skills/"*/SKILL.md; do
        [ -f "$skill" ] || continue
        install_file "$skill" "$root/skills/$(basename "$(dirname "$skill")")/SKILL.md"
    done
}

install_scripts() {
    local root="$1"
    local script

    for script in "$REPO_ROOT/scripts/"*.sh; do
        [ -f "$script" ] || continue
        install_file "$script" "$root/scripts/$(basename "$script")"
    done
}

install_templates() {
    local root="$1"
    local template

    for template in "$REPO_ROOT/templates/"*.yaml "$REPO_ROOT/templates/"*.md "$REPO_ROOT/templates/"*.toml "$REPO_ROOT/templates/"*.ndjson; do
        [ -f "$template" ] || continue
        install_file "$template" "$root/templates/$(basename "$template")"
    done
}

install_tools() {
    local root="$1"
    local tool
    local file
    for file in "$REPO_ROOT/tools/"*.py "$REPO_ROOT/tools/"*.txt; do
        [ -f "$file" ] || continue
        install_file "$file" "$root/tools/$(basename "$file")"
    done
    for tool in "$REPO_ROOT/tools/"*/; do
        [ -d "$tool" ] || continue
        while IFS= read -r -d '' file; do
            install_file "$file" "$root/tools/${file#"$REPO_ROOT/tools/"}"
        done < <(find "$tool" -type f ! -path '*/__pycache__/*' -print0)
    done
}
install_controller() {    local destination_root="$1"
    install_file "$REPO_ROOT/sync.sh" "$destination_root/sync.sh"
}

deploy_target() {
    local target="$1"
    local dest="${2:-.}"
    local config_root

    case "$target" in
        generic)
            config_root="$dest/.ctrust"
            install_agents_and_skills "$config_root"
            install_scripts "$config_root"
            install_templates "$config_root"
            install_tools "$config_root"
            install_controller "$config_root"
            ;;
        antigravity)
            install_agents_and_skills "$dest/.agents"
            install_scripts "$dest/.ctrust"
            install_templates "$dest/.ctrust"
            install_tools "$dest/.ctrust"
            install_controller "$dest/.ctrust"
            ;;
        opencode)
            install_agents_and_skills "$dest/.opencode"
            install_scripts "$dest/.ctrust"
            install_templates "$dest/.ctrust"
            install_tools "$dest/.ctrust"
            install_controller "$dest/.ctrust"
            ;;
        kilocode)
            install_agents_and_skills "$dest/.kilo"
            install_scripts "$dest/.ctrust"
            install_templates "$dest/.ctrust"
            install_tools "$dest/.ctrust"
            install_controller "$dest/.ctrust"
            ;;
        cursor)
            install_agents_and_skills "$dest/.cursor"
            install_scripts "$dest/.ctrust"
            install_templates "$dest/.ctrust"
            install_tools "$dest/.ctrust"
            install_controller "$dest/.ctrust"
            ;;
        claude)
            install_agents_and_skills "$dest/.claude"
            install_scripts "$dest/.ctrust"
            install_templates "$dest/.ctrust"
            install_tools "$dest/.ctrust"
            install_controller "$dest/.ctrust"
            ;;
        all)
            deploy_target generic "$dest"
            deploy_target antigravity "$dest"
            deploy_target opencode "$dest"
            deploy_target kilocode "$dest"
            deploy_target cursor "$dest"
            deploy_target claude "$dest"
            ;;
        *)
            echo "Unknown target: $target" >&2
            return 1
            ;;
    esac
}

remove_if_same() {
    local source="$1"
    local destination="$2"

    if [ -f "$destination" ] && cmp -s "$source" "$destination"; then
        rm -f "$destination"
        echo "  removed  $destination"
    elif [ -f "$destination" ]; then
        echo "  preserved $destination (content differs)"
    fi
}

clean_tree() {
    local root="$1"
    local agent
    local skill
    local script

    for agent in "$REPO_ROOT/agents/"*.md; do
        [ -f "$agent" ] || continue
        remove_if_same "$agent" "$root/agents/$(basename "$agent")"
    done
    for skill in "$REPO_ROOT/skills/"*/SKILL.md; do
        [ -f "$skill" ] || continue
        remove_if_same "$skill" "$root/skills/$(basename "$(dirname "$skill")")/SKILL.md"
    done
    for script in "$REPO_ROOT/scripts/"*.sh; do
        [ -f "$script" ] || continue
        remove_if_same "$script" "$root/scripts/$(basename "$script")"
    done
    for template in "$REPO_ROOT/templates/"*.yaml "$REPO_ROOT/templates/"*.md "$REPO_ROOT/templates/"*.toml "$REPO_ROOT/templates/"*.ndjson; do
        [ -f "$template" ] || continue
        remove_if_same "$template" "$root/templates/$(basename "$template")"
    done
    for file in "$REPO_ROOT/tools/"*.py "$REPO_ROOT/tools/"*.txt; do
        [ -f "$file" ] || continue
        remove_if_same "$file" "$root/tools/$(basename "$file")"
    done
    for tool in "$REPO_ROOT/tools/"*/; do
        [ -d "$tool" ] || continue
        while IFS= read -r -d '' file; do
            remove_if_same "$file" "$root/tools/${file#"$REPO_ROOT/tools/"}"
        done < <(find "$tool" -type f ! -path '*/__pycache__/*' -print0)
    done
    remove_if_same "$REPO_ROOT/sync.sh" "$root/sync.sh"
}

clean_target() {
    local target="$1"
    local dest="${2:-.}"

    case "$target" in
        generic)
            clean_tree "$dest/.ctrust"
            ;;
        antigravity)
            clean_tree "$dest/.agents"
            clean_tree "$dest/.ctrust"
            ;;
        opencode)
            clean_tree "$dest/.opencode"
            clean_tree "$dest/.ctrust"
            ;;
        kilocode)
            clean_tree "$dest/.kilo"
            clean_tree "$dest/.ctrust"
            ;;
        cursor)
            clean_tree "$dest/.cursor"
            clean_tree "$dest/.ctrust"
            ;;
        claude)
            clean_tree "$dest/.claude"
            clean_tree "$dest/.ctrust"
            ;;
        all)
            clean_target generic "$dest"
            clean_target antigravity "$dest"
            clean_target opencode "$dest"
            clean_target kilocode "$dest"
            clean_target cursor "$dest"
            clean_target claude "$dest"
            ;;
        *)
            echo "Unknown target to clean: $target" >&2
            return 1
            ;;
    esac
}

list_components() {
    echo "==> ctrust agents"
    for file in "$REPO_ROOT/agents/"*.md; do
        [ -f "$file" ] && echo "  $(basename "$file" .md)"
    done
    echo "==> ctrust skills"
    for file in "$REPO_ROOT/skills/"*/SKILL.md; do
        [ -f "$file" ] && echo "  $(basename "$(dirname "$file")")"
    done
    echo "==> ctrust templates"
    for file in "$REPO_ROOT/templates/"*.yaml "$REPO_ROOT/templates/"*.md "$REPO_ROOT/templates/"*.toml "$REPO_ROOT/templates/"*.ndjson; do
        [ -f "$file" ] && echo "  $(basename "$file")"
    done
    echo "==> ctrust scripts"
    for file in "$REPO_ROOT/scripts/"*.sh; do
        [ -f "$file" ] && echo "  $(basename "$file")"
    done
    echo "==> ctrust tools"
    for file in "$REPO_ROOT/tools/"*/*; do
        [ -f "$file" ] && echo "  ${file#"$REPO_ROOT/"}"
    done
}

verify() {
    local failed=0
    local file
    local component_root="$REPO_ROOT"
    local candidate

    # Client deployments keep agents/skills beside the .ctrust controller.
    # Prefer local components for the source repository and generic installs.
    if [ "$(basename "$REPO_ROOT")" = ".ctrust" ] && \
        [ ! -d "$component_root/agents" ] && [ ! -d "$component_root/skills" ]; then
        for candidate in .agents .opencode .kilo .cursor .claude; do
            candidate="$(dirname "$REPO_ROOT")/$candidate"
            if [ -d "$candidate/agents" ] && [ -d "$candidate/skills" ]; then
                component_root="$candidate"
                break
            elif [ "$component_root" = "$REPO_ROOT" ] && \
                { [ -d "$candidate/agents" ] || [ -d "$candidate/skills" ]; }; then
                component_root="$candidate"
            fi
        done
    fi

    for file in "$component_root/agents/"*.md "$component_root/skills/"*/SKILL.md "$REPO_ROOT/templates/"*.yaml "$REPO_ROOT/templates/"*.md "$REPO_ROOT/templates/"*.toml "$REPO_ROOT/templates/"*.ndjson "$REPO_ROOT/scripts/"*.sh; do
        if [ ! -f "$file" ]; then
            echo "Missing component: $file" >&2
            failed=1
        fi
    done

    for file in "$REPO_ROOT/scripts/"*.sh; do
        [ -f "$file" ] || continue
        if ! bash -n "$file"; then
            failed=1
        fi
    done

    for file in "$REPO_ROOT/tools/"*.py "$REPO_ROOT/tools/"*/*.py; do
        [ -f "$file" ] || continue
        if ! python3 -m py_compile "$file"; then
            failed=1
        fi
    done

    if [ "$failed" -eq 0 ]; then
        echo "ctrust verification passed"
    else
        echo "ctrust verification failed" >&2
        return 1
    fi
}

case "$CMD" in
    generic|antigravity|opencode|kilocode|cursor|claude|all)
        deploy_target "$CMD" "${2:-.}"
        ;;
    clean)
        clean_target "${2:-generic}" "${3:-.}"
        ;;
    list)
        list_components
        ;;
    init|inventory|recover|upgrade-state|status|status-slices|reconcile|reconcile-artifacts|validate-artifacts|plan-slices|organize|validate-organization|verify-slice|function-map|select-function|record-implementation|record-evidence|compare|resume|checkpoint|contract|model|next|failed)
        "$REPO_ROOT/scripts/ctrust-state.sh" "$CMD" "${2:-.}" "${3:-checkpoint}" "${4:-}" "${5:-}"
        ;;
    verify)
        verify
        ;;
    help|--help|-h)
        usage
        ;;
    *)
        echo "Unknown command or target: $CMD" >&2
        usage
        exit 1
        ;;
esac
